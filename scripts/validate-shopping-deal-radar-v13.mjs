import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
const root = process.cwd();
const source = (file) => fs.readFileSync(path.join(root, file), "utf8");
let checks = 0;
const check = (okay, message) => { assert.ok(okay, message); checks++; };
const api = source("services/platform-api/src/shopping/service.ts");
const routes = source("services/platform-api/src/shopping/routes.ts");
const radar = source("services/platform-api/src/shopping/deal-radar.ts");
const web = source("apps/shopping-web/app/deals/deal-radar-client.tsx");
const webPage = source("apps/shopping-web/app/deals/page.tsx");
const mobile = source("apps/shopping-mobile/app/deals.tsx");
const webHome = source("apps/shopping-web/app/shopping/page.tsx");
const mobileHome = source("apps/shopping-mobile/app/(tabs)/index.tsx");
const css = source("apps/shopping-web/app/shopping-deals-v13.css");
for (const marker of ['merchant: { vertical: "SHOPPING"', 'status: "ACTIVE"', 'take: 401', 'item.store?.status === "ACTIVE"', 'moreRecentCandidatesExist', 'pricingNote', 'curateDealRadar(']) check(api.includes(marker), `API integrity: ${marker}`);
for (const marker of ['/v1/shopping/deals', 'dealRadarQuerySchema.parse', 'minDiscountPercent', 'verifiedSeller', 'maxPriceMinor']) check(routes.includes(marker), `Typed endpoint: ${marker}`);
for (const marker of ['availableQuantity <= 0', 'seller?.verified', 'Number.isSafeInteger', 'before - now', 'fraction * 100', 'unique']) check(radar.includes(marker), `Pure offer curation: ${marker}`);
for (const marker of ['AbortController', 'retry', 'minDiscountPercent', 'maxPriceMinor', 'verifiedSeller', 'aria-live', 'moreRecentCandidatesExist', '<ProductCard', 'budgetError']) check(web.includes(marker), `Web UX: ${marker}`);
for (const marker of ['publicApi.get<RadarResponse>', 'useFocusEffect', 'signInWithBazId', 'setVariantQuantity', '<ProductCard', 'verifiedSeller', 'moreRecentCandidatesExist']) check(mobile.includes(marker), `Mobile parity: ${marker}`);
check(webPage.includes('DealRadarClient'), "Web page mounted");
check(webHome.includes('"/deals"'), "Shopping home advertises real deal hub");
check(mobileHome.includes('router.push("/deals")'), "Mobile home links to deal hub");
check(source("apps/shopping-mobile/app/_layout.tsx").includes('name="deals"'), "Native navigation registered");
check(source("apps/shopping-web/app/layout.tsx").includes('shopping-deals-v13.css'), "Global V13 CSS loaded");
check(css.includes('@media(max-width:620px)') && css.includes('prefers-reduced-motion'), "Mobile/reduced motion support");
const tests = spawnSync(process.execPath, ["--experimental-strip-types", "--test", "--test-reporter=tap", "scripts/shopping-deal-radar-v13.test.mjs"], { cwd: root, encoding: "utf8" });
if (tests.status !== 0) { console.error(tests.stdout, tests.stderr); process.exit(tests.status ?? 1); }
const pass = tests.stdout.match(/^# pass\s+(\d+)\s*$/m);
const fail = tests.stdout.match(/^# fail\s+(\d+)\s*$/m);
const count = tests.stdout.match(/^# tests\s+(\d+)\s*$/m);
if (!pass || !fail || !count) console.error(tests.stdout, tests.stderr);
check(Number(pass?.[1]) === 8 && Number(fail?.[1]) === 0 && Number(count?.[1]) === 8, "Eight offer curation unit tests passed");
console.log(`Shopping Deal Radar V13 validation PASS (${checks} source assertions; 8 behavior tests).`);
